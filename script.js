function groupByTier(mode){const groups={"Tier 1":[],"Tier 2":[],"Tier 3":[],"Tier 4":[],"Tier 5":[]};(allData[mode]||[]).forEach(p=>{const t=p.tier||"-";if(t.includes("1"))groups["Tier 1"].push(p);else if(t.includes("2"))groups["Tier 2"].push(p);else if(t.includes("3"))groups["Tier 3"].push(p);else if(t.includes("4"))groups["Tier 4"].push(p);else groups["Tier 5"].push(p)});return groups}
function renderTierColumns(){const q=searchInput.value.trim().toLowerCase();const groups=groupByTier(currentMode);tierColumns.innerHTML=Object.entries(groups).map(([tier,players],idx)=>{const filtered=players.filter(p=>p.name.toLowerCase().includes(q));const tierNo=idx+1;return `<section class="tier-col tier-${tierNo}"><header><img src="${iconPath(tierNo<=3?"overall.svg":(MODE_ICON_FILES[currentMode]||"overall.svg"))}" alt=""><h2>${tier}</h2></header><div class="tier-list">${filtered.map((p,i)=>`<div class="tier-player" data-player="${escapeHtml(p.name)}" data-rank="${i+1}" data-mode="${escapeHtml(currentMode)}"><img src="${avatar(p.name,48)}" alt=""><b>${escapeHtml(p.name)}</b><em>⌃</em><small>${escapeHtml(p.tier||"-")}</small></div>`).join("")||`<div class="empty small-empty">No players</div>`}</div></section>`}).join("");document.querySelectorAll(".tier-player").forEach(row=>row.addEventListener("click",()=>openPlayer(row.dataset.player,Number(row.dataset.rank),row.dataset.mode)))}

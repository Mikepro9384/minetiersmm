function iconPath(file){return `assets/icons/${file}`}
function playSound(sound){try{sound.currentTime=0;sound.volume=.34;sound.play()}catch(e){}}
function escapeHtml(value){return String(value??"").replace(/[&<>"']/g,s=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#039;"}[s]))}
function avatar(name,size=64){return `https://mc-heads.net/avatar/${encodeURIComponent(name)}/${size}`}
function skin(name){return `https://mc-heads.net/body/${encodeURIComponent(name)}/80`}
function normalizeName(name){return String(name||"").trim().toLowerCase()}
function allPlayerRecords(){const map=new Map();Object.values(allData).flat().forEach(p=>{if(!map.has(normalizeName(p.name)))map.set(normalizeName(p.name),p)});return [...map.values()]}
function findPlayer(name){return allPlayerRecords().find(p=>normalizeName(p.name)===normalizeName(name)) || {name}}
function getTier(playerName,mode){const p=(allData[mode]||[]).find(x=>normalizeName(x.name)===normalizeName(playerName));return p?.tier||"-"}
function overallPoints(playerName){const p=(allData.Overall||[]).find(x=>normalizeName(x.name)===normalizeName(playerName));return Number(p?.pts)||0}
function tierClass(tier){if(tier==="-")return"none";if(tier.includes("1"))return"gold";if(tier.includes("2"))return"silver";if(tier.includes("3"))return"bronze";if(tier.includes("4"))return"blue";return"dark"}
function combatTitleByPoints(points){if(points>=400)return"Combat Grandmaster";if(points>=250)return"Combat Master";if(points>=100)return"Combat Ace";if(points>=50)return"Combat Specialist";if(points>=20)return"Combat Cadet";if(points>=10)return"Combat Novice";return"Rookie"}
function combatTitle(rank,points){if(rank===1)return"Combat Grandmaster";if(rank<=4)return"Combat Master";if(rank<=8)return"Combat Ace";return combatTitleByPoints(points)}
function tierBadges(name){return MODE_ORDER.map(mode=>{const t=getTier(name,mode);return `<span class="tier-badge ${tierClass(t)}"><img src="${iconPath(MODE_ICON_FILES[mode])}" alt="${mode}"><b>${escapeHtml(t)}</b></span>`}).join("")}
